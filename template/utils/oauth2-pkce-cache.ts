/**
 * oauth2-pkce-cache.ts — OAuth2 Authorization Code + PKCE flow (user-facing)
 *
 * Implements the OAuth2 `authorization_code` grant with PKCE (RFC 7636) for
 * user-facing browser flows. Distinct from `oauth2-client-credentials-cache.ts`
 * because PKCE is *interactive*: redirect → user consents → callback receives code
 * → exchange for tokens. No client secret required on the public client.
 *
 * Workers-compatible: uses Web Crypto + fetch only — zero Node.js built-ins.
 *
 * Typical flow:
 *   1. Generate PKCE pair: `const { verifier, challenge } = await generatePkceVerifierAndChallenge()`
 *   2. Store `verifier` in `sessionStorage` (client) — NEVER in a cookie.
 *   3. Redirect user to `client.getAuthorizeUrl({ challenge, state })`.
 *   4. On callback: `const tokens = await client.exchangeCodeForToken(code, verifier)`.
 *   5. On 401: `const fresh = await client.refreshToken(tokens.refresh_token)`.
 *
 * @module oauth2-pkce-cache
 *
 * @example
 *   // In the login handler (Worker or edge function)
 *   const client = createAuth0PkceClient({
 *     domain: env.AUTH0_DOMAIN,
 *     clientId: env.AUTH0_CLIENT_ID,
 *     redirectUri: "https://app.example.com/auth/callback",
 *     audience: env.AUTH0_AUDIENCE,
 *   });
 *
 *   // Step 1 — build the authorize URL
 *   const { verifier, challenge } = await generatePkceVerifierAndChallenge();
 *   // persist `verifier` in sessionStorage on the client side before redirect
 *   const url = client.getAuthorizeUrl({ challenge, state: crypto.randomUUID() });
 *   return Response.redirect(url, 302);
 *
 *   // Step 2 — in the /auth/callback handler
 *   const { code } = new URL(request.url).searchParams;
 *   const verifier = getFromSessionStorage("pkce_verifier"); // client passes it back
 *   const tokens = await client.exchangeCodeForToken(code, verifier);
 *   // store tokens.access_token, tokens.refresh_token securely (HttpOnly cookie / KV)
 */

// ---------------------------------------------------------------------------
// Error
// ---------------------------------------------------------------------------

/** Thrown on any PKCE OAuth2 failure (network, token error, invalid response). */
export class Oauth2PkceError extends Error {
  readonly status?: number;
  readonly body?: string;

  constructor(message: string, opts?: { status?: number; body?: string }) {
    super(message);
    this.name = "Oauth2PkceError";
    this.status = opts?.status;
    this.body = opts?.body;
  }
}

