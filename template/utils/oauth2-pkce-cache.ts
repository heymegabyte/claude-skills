/**
 * Generate a cryptographically secure PKCE verifier + S256 challenge pair.
 *
 * Uses Web Crypto (available in CF Workers, browsers, and Node 20+).
 * The verifier is 96 random bytes → 128-char base64url string (well within RFC bounds).
 *
 * @example
 *   const { verifier, challenge, method } = await generatePkceVerifierAndChallenge();
 *   sessionStorage.setItem("pkce_verifier", verifier);
 *   const url = client.getAuthorizeUrl({ challenge, state: crypto.randomUUID() });
 */
export async function generatePkceVerifierAndChallenge(): Promise<PkceVerifierAndChallenge> {
  // 96 random bytes → 128-char base64url verifier (RFC 7636 §4.1: 43-128 chars)
  const randomBytes = new Uint8Array(96);
  crypto.getRandomValues(randomBytes);
  const verifier = base64UrlEncode(randomBytes);

  // S256 = BASE64URL(SHA256(ASCII(verifier)))
  const encoded = new TextEncoder().encode(verifier);
  const digest = await crypto.subtle.digest("SHA-256", encoded);
  const challenge = base64UrlEncode(new Uint8Array(digest));

  return { verifier, challenge, method: "S256" };
}

