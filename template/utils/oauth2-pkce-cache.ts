/** Options for {@link createAuth0PkceClient}. */
export interface Auth0PkceClientOptions {
  /** Auth0 domain, e.g. `"my-tenant.us.auth0.com"`. No trailing slash. */
  domain: string;
  /** Auth0 application Client ID (public — safe to expose in browser). */
  clientId: string;
  /** Where Auth0 will redirect after user consents. Must be allow-listed in Auth0. */
  redirectUri: string;
  /**
   * Auth0 API audience, e.g. `"https://api.example.com"`.
   * Required when exchanging for an access token scoped to your API.
   */
  audience?: string;
  /** Space-separated scopes. Defaults to `"openid profile email"`. */
  scope?: string;
}

/** Additional parameters for {@link Auth0PkceClient.getAuthorizeUrl}. */
export interface GetAuthorizeUrlOptions {
  /** PKCE code challenge (S256 hash of the verifier). */
  challenge: string;
  /** Opaque CSRF state token. Verify this on callback. */
  state: string;
  /** Override the default scope for this specific authorization request. */
  scope?: string;
}

/** Successful token response from Auth0. */
export interface PkceTokenResponse {
  access_token: string;
  /** Present when `offline_access` scope was requested. */
  refresh_token?: string;
  id_token?: string;
  token_type: string;
  expires_in: number;
  scope?: string;
}

/** PKCE verifier/challenge pair generated by {@link generatePkceVerifierAndChallenge}. */
export interface PkceVerifierAndChallenge {
  /** Random 43-128 char URL-safe string. Store in sessionStorage; never send to server. */
  verifier: string;
  /** S256 hash of the verifier. Safe to include in the authorize URL. */
  challenge: string;
  /** Always `"S256"`. Included so callers can pass it to the authorize URL without magic strings. */
  method: "S256";
}

/** The client object returned by {@link createAuth0PkceClient}. */
export interface Auth0PkceClient {
  /**
   * Build the Auth0 authorize URL to which the browser should be redirected.
   * Include the `state` param and verify it on callback to prevent CSRF.
   */
  getAuthorizeUrl(opts: GetAuthorizeUrlOptions): string;

  /**
   * Exchange an authorization `code` (received on the callback URL) for tokens.
   * Requires the original `codeVerifier` that generated the challenge.
   *
   * @throws {Oauth2PkceError} on HTTP error or malformed response.
   */
  exchangeCodeForToken(code: string, codeVerifier: string): Promise<PkceTokenResponse>;

  /**
   * Use a `refresh_token` to obtain a fresh `access_token`.
   * Requires the `offline_access` scope to have been granted.
   *
   * @throws {Oauth2PkceError} on HTTP error or missing refresh_token.
   */
  refreshToken(refreshToken: string): Promise<PkceTokenResponse>;
}

