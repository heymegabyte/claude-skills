/**
 * Create an Auth0 PKCE client scoped to a single tenant + application.
 *
 * The client object is lightweight and stateless — create it per-request in a
 * Worker, or once at module level if domain/clientId never change.
 *
 * @example
 *   const client = createAuth0PkceClient({
 *     domain: "my-tenant.us.auth0.com",
 *     clientId: "abc123",
 *     redirectUri: "https://app.example.com/auth/callback",
 *     audience: "https://api.example.com",
 *   });
 *
 *   // In the login route:
 *   const { verifier, challenge } = await generatePkceVerifierAndChallenge();
 *   const authorizeUrl = client.getAuthorizeUrl({ challenge, state: crypto.randomUUID() });
 *
 *   // In the callback route:
 *   const tokens = await client.exchangeCodeForToken(code, verifier);
 */
export function createAuth0PkceClient(opts: Auth0PkceClientOptions): Auth0PkceClient {
  const {
    domain,
    clientId,
    redirectUri,
    audience,
    scope: defaultScope = "openid profile email",
  } = opts;

  const issuerBase = `https://${domain}`;
  const authorizeEndpoint = `${issuerBase}/authorize`;
  const tokenEndpoint = `${issuerBase}/oauth/token`;

  return {
    getAuthorizeUrl({ challenge, state, scope }: GetAuthorizeUrlOptions): string {
      const params = new URLSearchParams({
        response_type: "code",
        client_id: clientId,
        redirect_uri: redirectUri,
        scope: scope ?? defaultScope,
        state,
        code_challenge: challenge,
        code_challenge_method: "S256",
      });
      if (audience) params.set("audience", audience);
      return `${authorizeEndpoint}?${params.toString()}`;
    },

    async exchangeCodeForToken(
      code: string,
      codeVerifier: string
    ): Promise<PkceTokenResponse> {
      const body: Record<string, string> = {
        grant_type: "authorization_code",
        client_id: clientId,
        code,
        redirect_uri: redirectUri,
        code_verifier: codeVerifier,
      };
      if (audience) body.audience = audience;
      return _postToken(tokenEndpoint, body);
    },

    async refreshToken(refreshToken: string): Promise<PkceTokenResponse> {
      return _postToken(tokenEndpoint, {
        grant_type: "refresh_token",
        client_id: clientId,
        refresh_token: refreshToken,
      });
    },
  };
}

