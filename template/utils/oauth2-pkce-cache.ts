/** POST to a token endpoint with `application/x-www-form-urlencoded` body. */
async function _postToken(
  endpoint: string,
  body: Record<string, string>
): Promise<PkceTokenResponse> {
  let response: Response;
  try {
    response = await fetch(endpoint, {
      method: "POST",
      headers: { "Content-Type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams(body).toString(),
    });
  } catch (err) {
    throw new Oauth2PkceError(`Network error reaching ${endpoint}: ${String(err)}`);
  }

  const text = await response.text();
  if (!response.ok) {
    throw new Oauth2PkceError(
      `Token endpoint returned ${response.status}: ${text.slice(0, 200)}`,
      { status: response.status, body: text }
    );
  }

  let json: unknown;
  try {
    json = JSON.parse(text);
  } catch {
    throw new Oauth2PkceError(`Token endpoint returned non-JSON: ${text.slice(0, 200)}`);
  }

  const tokenResp = json as Record<string, unknown>;
  if (typeof tokenResp.access_token !== "string" || typeof tokenResp.token_type !== "string") {
    throw new Oauth2PkceError(
      `Token response missing required fields: ${JSON.stringify(Object.keys(tokenResp))}`
    );
  }

  return tokenResp as unknown as PkceTokenResponse;
}

/** Encode a Uint8Array to a URL-safe base64 string (no padding). */
function base64UrlEncode(bytes: Uint8Array): string {
  let str = "";
  for (let i = 0; i < bytes.length; i++) {
    str += String.fromCharCode(bytes[i]);
  }
  return btoa(str).replace(/\+/g, "-").replace(/\//g, "_").replace(/=/g, "");
}

